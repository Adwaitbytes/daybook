// Builds src/generated/deployments.ts from the deployment records other parts of the repo publish:
//   1. ../contracts/deployments/*.json (preferred), any JSON that names a DaybookReactive address with a chain id
//   2. ../docs/DEPLOYMENTS.md, a markdown table row that mentions DaybookReactive, the network and an address
// Only the reactive contract's address is taken from the record. Everything else (factory, tills, policies,
// invoices) is read from chain at request time, so a stale record can never show a wrong pay address.
// If neither source has an address the file says so and the site renders its "not deployed yet" state.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const dest = join(here, "..", "src", "generated", "deployments.ts");

const NETWORKS = { 5318007: "lasna", 1597: "mainnet" };
const ADDRESS = /0x[0-9a-fA-F]{40}/;

/** Walks a parsed JSON value and collects { chainId, address, block } for every DaybookReactive it names. */
function fromJson(value, file, inherited = {}) {
  const found = [];
  if (value === null || typeof value !== "object") return found;
  const ctx = { ...inherited };
  for (const k of ["chainId", "chain_id", "chain"]) {
    const v = value[k];
    if (typeof v === "number" || (typeof v === "string" && /^\d+$/.test(v))) ctx.chainId = Number(v);
  }
  for (const [k, v] of Object.entries(value)) {
    if (/^daybookreactive$/i.test(k)) {
      const address = typeof v === "string" ? v : v?.address;
      const block = typeof v === "object" ? (v?.block ?? v?.blockNumber ?? v?.deployBlock) : undefined;
      if (typeof address === "string" && ADDRESS.test(address)) {
        found.push({ chainId: ctx.chainId, address: address.match(ADDRESS)[0], block, source: file });
      }
    } else if (typeof v === "object") {
      found.push(...fromJson(v, file, ctx));
    }
  }
  if (typeof value.contractName === "string" && /^DaybookReactive$/.test(value.contractName)) {
    const a = value.address ?? value.contractAddress;
    if (typeof a === "string" && ADDRESS.test(a)) found.push({ chainId: ctx.chainId, address: a, source: file });
  }
  return found;
}

function fromMarkdown(text, file) {
  const found = [];
  for (const line of text.split("\n")) {
    if (!/DaybookReactive/.test(line)) continue;
    const m = line.match(ADDRESS);
    if (m === null) continue;
    const chainId = /lasna|5318007/i.test(line) ? 5318007 : /mainnet|1597/i.test(line) ? 1597 : undefined;
    found.push({ chainId, address: m[0], source: file });
  }
  return found;
}

const records = [];
const jsonDir = join(root, "contracts", "deployments");
if (existsSync(jsonDir)) {
  for (const f of readdirSync(jsonDir)
    .filter((x) => x.endsWith(".json"))
    .sort()) {
    const rel = `contracts/deployments/${f}`;
    records.push(...fromJson(JSON.parse(readFileSync(join(jsonDir, f), "utf8")), rel));
  }
}
const md = join(root, "docs", "DEPLOYMENTS.md");
if (records.length === 0 && existsSync(md))
  records.push(...fromMarkdown(readFileSync(md, "utf8"), "docs/DEPLOYMENTS.md"));

const byNetwork = {};
for (const r of records) {
  const net = NETWORKS[r.chainId];
  if (net === undefined) continue;
  // The last record for a network wins, so an appended redeploy replaces the earlier one.
  byNetwork[net] = {
    reactive: r.address,
    deployBlock: r.block === undefined ? null : String(r.block),
    source: r.source,
  };
}

const entry = (n) =>
  byNetwork[n] === undefined
    ? "null"
    : `{ reactive: "${byNetwork[n].reactive}", deployBlock: ${byNetwork[n].deployBlock === null ? "null" : `"${byNetwork[n].deployBlock}"`}, source: "${byNetwork[n].source}" }`;

writeFileSync(
  dest,
  `// Generated by scripts/gen-deployments.mjs. Do not edit by hand; rerun \`pnpm gen\` after a deployment.
import type { DeploymentRecord } from "@/lib/deployment-types";

export const generatedDeployments: { lasna: DeploymentRecord | null; mainnet: DeploymentRecord | null } = {
  lasna: ${entry("lasna")},
  mainnet: ${entry("mainnet")},
};
`,
);
console.log(
  `deployments: lasna=${byNetwork.lasna?.reactive ?? "none"} mainnet=${byNetwork.mainnet?.reactive ?? "none"}`,
);
