// Copies ABIs (and the creation bytecode the "Make your own" wizard deploys) from the Foundry build in
// ../contracts/out into src/generated. Run `forge build` in ../contracts first. The output is committed so the
// web app builds without Foundry; rerun after any contract change.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "..", "contracts", "out");
const dest = join(here, "..", "src", "generated");

function artifact(name) {
  const path = join(out, `${name}.sol`, `${name}.json`);
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (err) {
    throw new Error(`cannot read ${path}; run forge build in daybook/contracts first (${err.message})`);
  }
}

const header = "// Generated by scripts/gen-abis.mjs from daybook/contracts/out. Do not edit by hand.\n\n";
const abis = ["DaybookReactive", "DaybookTill", "PayAddressFactory"];
let abiSrc = header;
for (const name of abis) {
  const a = artifact(name);
  const key = name[0].toLowerCase() + name.slice(1);
  abiSrc += `export const ${key}Abi = ${JSON.stringify(a.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(dest, "abis.ts"), abiSrc);

let codeSrc = header;
for (const name of abis) {
  const a = artifact(name);
  const hex = a.bytecode?.object;
  if (typeof hex !== "string" || !hex.startsWith("0x") || hex.length < 4) throw new Error(`${name} has no bytecode`);
  const key = name[0].toLowerCase() + name.slice(1);
  codeSrc += `export const ${key}Bytecode = "${hex}" as const;\n\n`;
}
writeFileSync(join(dest, "bytecode.ts"), codeSrc);
console.log(`wrote ${abis.length} ABIs and bytecodes to src/generated`);
